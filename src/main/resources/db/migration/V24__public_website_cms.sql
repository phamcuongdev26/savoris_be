ALTER TABLE branches ADD COLUMN IF NOT EXISTS slug varchar(80);
UPDATE branches SET slug = CASE WHEN code ~ '^CN0[1-4]$' THEN 'cn' || right(code, 1) ELSE lower(code) END WHERE slug IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_branches_slug ON branches(slug);

CREATE TABLE IF NOT EXISTS site_setting (
    id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS branch_page (
    branch_id integer PRIMARY KEY REFERENCES branches(id),
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS offer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(id),
    title varchar(180) NOT NULL,
    description text NOT NULL DEFAULT '',
    price bigint,
    unit varchar(30) NOT NULL DEFAULT 'người',
    schedule varchar(255) NOT NULL DEFAULT '',
    image_url varchar(1000),
    image_alt varchar(255) NOT NULL DEFAULT '',
    menu_url varchar(1000),
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS gallery_image (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer REFERENCES branches(id),
    image_url varchar(1000) NOT NULL,
    alt varchar(255) NOT NULL,
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS accolade (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(id),
    award_year integer NOT NULL,
    content varchar(500) NOT NULL,
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS testimonial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(id),
    quote text NOT NULL,
    reviewer varchar(180) NOT NULL,
    title varchar(180) NOT NULL DEFAULT '',
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS menu_file (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(id),
    title varchar(180) NOT NULL,
    file_url varchar(1000) NOT NULL,
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS opening_hour (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(id),
    weekday integer NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    opens_at time,
    closes_at time,
    closed boolean NOT NULL DEFAULT false,
    UNIQUE (branch_id, weekday)
);

